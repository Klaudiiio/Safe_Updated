BEGIN;

CREATE TABLE public."user" (
    user_id bigint PRIMARY KEY,
    username text NOT NULL UNIQUE,
    name text NOT NULL,
    student_id text,
    course text,
    phone_number text,
    user_type text NOT NULL DEFAULT 'USER',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.incident_types (
    incident_types_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_name text NOT NULL UNIQUE,
    priority_level text NOT NULL,
    description text
);

CREATE TABLE public.location (
    location_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building text NOT NULL,
    room text,
    latitude double precision,
    longitude double precision
);

CREATE TABLE public.responder (
    responders_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    department text,
    contact_number text,
    availability_status text NOT NULL DEFAULT 'AVAILABLE',
    user_type text NOT NULL DEFAULT 'CLINIC_STAFF'
);

CREATE TABLE public.incident (
    incident_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public."user"(user_id) ON DELETE SET NULL,
    incident_types_id bigint REFERENCES public.incident_types(incident_types_id) ON DELETE RESTRICT,
    location_id bigint REFERENCES public.location(location_id) ON DELETE SET NULL,
    location_description text,
    description text,
    attachment_url text,
    status text NOT NULL DEFAULT 'PENDING',
    reported_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.notification (
    notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id bigint NOT NULL REFERENCES public.incident(incident_id) ON DELETE CASCADE,
    notification_type text NOT NULL,
    target text,
    message text,
    priority text,
    delivery_status text NOT NULL DEFAULT 'PENDING',
    sent_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.responder_notification (
    responder_notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id bigint NOT NULL REFERENCES public.notification(notification_id) ON DELETE CASCADE,
    responders_id bigint NOT NULL REFERENCES public.responder(responders_id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'PENDING',
    assigned_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (notification_id, responders_id)
);

CREATE TABLE public.admin (
    admin_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES public."user"(user_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.logs (
    log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id bigint REFERENCES public.incident(incident_id) ON DELETE SET NULL,
    responders_id bigint REFERENCES public.responder(responders_id) ON DELETE SET NULL,
    action text NOT NULL,
    action_time timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX incident_reported_at_idx ON public.incident (reported_at DESC);
CREATE INDEX incident_user_id_idx ON public.incident (user_id);
CREATE INDEX incident_location_id_idx ON public.incident (location_id);
CREATE INDEX notification_sent_at_idx ON public.notification (sent_at DESC);
CREATE INDEX logs_action_time_idx ON public.logs (action_time DESC);

ALTER TABLE public."user" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.incident_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.incident ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.location ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notification ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.responder_notification ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.responder ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.logs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE
    public."user",
    public.incident_types,
    public.incident,
    public.location,
    public.notification,
    public.responder_notification,
    public.responder,
    public.admin,
    public.logs
FROM anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
    public."user",
    public.incident_types,
    public.incident,
    public.location,
    public.notification,
    public.responder_notification,
    public.responder,
    public.admin,
    public.logs
TO service_role;

GRANT USAGE, SELECT ON SEQUENCE
    public.incident_types_incident_types_id_seq,
    public.location_location_id_seq,
    public.responder_responders_id_seq,
    public.incident_incident_id_seq,
    public.notification_notification_id_seq,
    public.responder_notification_responder_notification_id_seq,
    public.admin_admin_id_seq,
    public.logs_log_id_seq
TO service_role;

COMMIT;
